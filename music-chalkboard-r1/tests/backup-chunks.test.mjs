import assert from 'node:assert/strict';
import {createScene} from '../src/scene-model.js';
import {createLesson} from '../src/lesson-model.js';
import {splitBackupScenes} from '../src/backup-chunks.js';
import {MAX_FILE_BYTES,validateBackupSet} from '../src/scene-storage.js';
const source=createScene();
const scenes=Array.from({length:1000},(_,i)=>({...structuredClone(source),id:`sample-${i}`}));
const packages=splitBackupScenes(scenes,{playMode:'step'});
assert.deepEqual(packages.map(p=>p.scenes.length),[500,500]);
assert.deepEqual(packages.flatMap(p=>p.scenes.map(s=>s.id)),scenes.map(s=>s.id));
for(const p of packages)assert.ok(new TextEncoder().encode(JSON.stringify(p)).length<=MAX_FILE_BYTES);
const firstLesson=createLesson({title:'두 파일에 흩어질 장면',sceneIds:[scenes[500].id,scenes[0].id]});
const secondLesson=createLesson({title:'같은 장면을 쓰는 수업',sceneIds:[scenes[500].id,scenes[999].id]});
const grouped=splitBackupScenes(scenes,{soundEnabled:false},{lessons:[firstLesson,secondLesson]});
assert.deepEqual(grouped.map(part=>part.scenes.length),[500,500]);
assert.deepEqual(grouped[0].lessons.map(lesson=>lesson.id),[firstLesson.id,secondLesson.id]);
for(const id of [scenes[0].id,scenes[500].id,scenes[999].id]) assert.ok(grouped[0].scenes.some(scene=>scene.id===id));
assert.deepEqual(validateBackupSet(grouped.toReversed()).scenes.map(scene=>scene.id),scenes.map(scene=>scene.id));
assert.equal(validateBackupSet(grouped).complete,true);
assert.equal(validateBackupSet([grouped[1]]).complete,false);
assert.throws(()=>validateBackupSet([grouped[0],grouped[0]]),/서로 다른/);
assert.throws(()=>validateBackupSet([grouped[0],packages[1]]),/같은 분할/);
assert.throws(()=>splitBackupScenes(scenes.slice(1),null,{lessons:[firstLesson]}),/빠진 장면/);
const threeParts=splitBackupScenes([...scenes,{...source,id:'last-scene'}]);
assert.throws(()=>validateBackupSet([threeParts[0],threeParts[1]]),/빠진 파일/);
console.log('1,000개 장면 분할 백업과 순서 테스트 통과');
