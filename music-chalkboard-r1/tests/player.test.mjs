import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { createScene } from '../src/scene-model.js';
const win = new Window({url:'http://localhost/'});
Object.assign(globalThis, {window:win,document:win.document,innerWidth:1200,devicePixelRatio:1,matchMedia:()=>({matches:true}),requestAnimationFrame:()=>1,cancelAnimationFrame:()=>{}});
const ctx=new Proxy({createImageData:(w,h)=>({data:new Uint8ClampedArray(w*h*4),width:w,height:h}),measureText:s=>({width:s.length*12}),createPattern:()=>null,createLinearGradient:()=>({addColorStop(){}}),createRadialGradient:()=>({addColorStop(){}})}, {get(t,p){return p in t?t[p]:(()=>{});},set(t,p,v){t[p]=v;return true;}});
win.HTMLCanvasElement.prototype.getContext=()=>ctx;
const stage=document.createElement('div'), frame=document.createElement('div'), board=document.createElement('canvas'), ink=document.createElement('div'), dust=document.createElement('canvas');
Object.defineProperty(stage,'clientWidth',{value:800}); stage.append(board,ink,dust);frame.append(stage);document.body.append(frame);
const {ScenePlayer}=await import('../src/player.js');
const player=new ScenePlayer({stage,frame,board,ink,dust});
const scene=createScene('text-explanation');scene.question='첫 번째 질문입니다.';scene.caption='마지막 정리입니다.';
const {defaultSteps}=await import('../src/scene-model.js');scene.steps=defaultSteps(scene);
player.open(scene);assert.equal(player.state,'ready');assert.equal(player.completed,0);
player.mode='continuous';player.next();assert.equal(player.completed,1);assert.equal(player.state,'waiting','reduced motion must reveal only one step');
player.next();assert.equal(player.completed,2);player.previous();assert.equal(player.completed,1);assert.equal(player.state,'waiting');
player.finish();assert.equal(player.state,'completed');assert.equal(player.completed,scene.steps.length);
player.previous();assert.equal(player.completed,scene.steps.length-1);
player.restart();assert.equal(player.state,'ready');assert.equal(player.completed,0);
const snap=player.snapshot();player.next();player.restore(snap);assert.equal(player.completed,0);
console.log('판서 시작·단계·되감기·완성·동작 줄이기 테스트 통과');
