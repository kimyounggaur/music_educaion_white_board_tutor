import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
const win = new Window({url:'http://localhost/'});
Object.assign(globalThis,{window:win,document:win.document});
const {openSceneList,searchScenes} = await import('../src/ui/scene-list.js');
const scene=(id,title,origin,extra={})=>({id,title,origin,deletedAt:null,templateId:'text-explanation',steps:[],tags:[],content:{blocks:[]},...extra});
const builtins=[scene('builtin:1','으뜸화음','builtin',{tags:['기초']})];
const scenes=[scene('user:1','으뜸화음 실습','user',{question:'도 미 솔'}),scene('user:2','숨김 으뜸화음','user',{deletedAt:'2026-11-17T00:00:00.000Z'})];
assert.deepEqual(searchScenes([...builtins,...scenes], '으뜸화음').map(x=>x.id),['builtin:1','user:1','user:2']);
const joined = scene('joined', '구성음 찾기', 'user', {question:'도·미·솔'});
assert.equal(searchScenes([joined], '도미솔').length, 1);
const chromatic = [scene('sharp','C# 화음','user'), scene('flat','Bb 화음','user'), scene('dominant','V7 화음','user')];
assert.deepEqual(searchScenes(chromatic, 'C#').map(item=>item.id), ['sharp']);
assert.deepEqual(searchScenes(chromatic, 'Bb').map(item=>item.id), ['flat']);
assert.deepEqual(searchScenes(chromatic, 'V7').map(item=>item.id), ['dominant']);
let opened;
const list=openSceneList({query:'으뜸화음',data:async()=>({builtins,scenes,order:['user:1']}),onOpen:(s,ids)=>{opened={s,ids};}});
await list.refresh();
assert.equal(list.element.querySelector('[role=tab][aria-selected=true]').textContent,'전체 검색');
assert.deepEqual([...list.element.querySelectorAll('li strong')].map(x=>x.textContent),['으뜸화음','으뜸화음 실습']);
assert.match(list.element.querySelector('ul').textContent,/기본 장면/);assert.match(list.element.querySelector('ul').textContent,/내 장면/);
list.element.querySelectorAll('li button')[1].click();await new Promise(r=>setTimeout(r,0));
assert.equal(opened.s.id,'user:1');assert.deepEqual(opened.ids,['builtin:1','user:1']);
const many=Array.from({length:35},(_,i)=>scene(`user:${i}`,`연습 ${i}`,'user'));
const list2=openSceneList({query:'연습',data:async()=>({builtins:[],scenes:many,order:[]})});await list2.refresh();
assert.equal(list2.element.querySelectorAll('li strong').length,30);
const more=[...list2.element.querySelectorAll('li button')].find(x=>x.textContent.includes('전체 목록 열기'));assert.ok(more);more.click();assert.equal(list2.element.querySelectorAll('li strong').length,35);
const input=list2.element.querySelector('input[type=search]');input.dispatchEvent(new win.CompositionEvent('compositionstart',{bubbles:true}));input.value='없는 내용';input.dispatchEvent(new win.Event('input',{bubbles:true}));input.dispatchEvent(new win.KeyboardEvent('keydown',{key:'Enter',bubbles:true,isComposing:true}));assert.equal(list2.element.querySelectorAll('li strong').length,35);
input.dispatchEvent(new win.CompositionEvent('compositionend',{bubbles:true}));await new Promise(r=>setTimeout(r,180));assert.match(list2.element.querySelector('ul').textContent,/다른 말로 검색/);
list2.close();
